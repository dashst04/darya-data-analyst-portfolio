-- Задание 6
-- Обновления приложений на Android и iOS
-- Используя CTE, найдем максимальную версию приложений среди всех приложений с поддержкой iOS и Android
WITH latest_version AS (
	SELECT usage_platform_ru AS platform, -- платформа
		   max(app_version) AS max_version -- находим максимальную версию приложения
	FROM source_db.audition
	WHERE (app_version IS NOT NULL AND app_version != '') AND (usage_platform_ru = 'Букмейт Android' OR usage_platform_ru = 'Букмейт iOS') -- исключаем пустые строки и оставляем только мобильные приложения 
	GROUP BY platform -- группируем по платформе
),
-- С помощью СТЕ для каждого пользователя находим версию приложения из последней активной сессии
user_versions AS ( 
	SELECT puid, -- пользователь
		   usage_platform_ru AS platform, -- платформа
		   argMax(app_version,msk_business_dt_str) AS latest_version, -- находим версию приложения из последнее сессии
		   uniqExact(usage_platform_ru) OVER (PARTITION BY puid) AS platforms_count -- Считаем количество платформ для каждого пользователя, чтобы потом исключить тех, кто пользуется несколькими платформами
	FROM source_db.audition
	WHERE (app_version IS NOT NULL AND app_version != '') AND (usage_platform_ru = 'Букмейт Android' OR usage_platform_ru = 'Букмейт iOS') -- исключаем пустые строки и оставляем только мобильные приложения
	GROUP BY puid,platform -- группируем по пользователю и платформе
),
-- В этом СТЕ, сравниваем версию приложения пользователя с максимальной версией приложения для каждой платформы
is_latest_version AS ( 
	SELECT uv.puid, -- пользователь
		uv.platform, -- платформ
		uv.latest_version = lv.max_version AS is_latest -- сравниваем версии приложении и выводим результат, где 1 - версии совпадают, 0 - нет.
	FROM user_versions uv
	JOIN latest_version lv ON uv.platform = lv.platform -- присоединяем latest_version по платформе
	WHERE platforms_count = 1 -- исключаем пользователей с несколькими платформами
)
SELECT IF(platform LIKE '%iOS','iOS','Android') AS os, -- группируем по ОС iOS/Android
	   round((countDistinctIf(puid, is_latest) / countDistinct(puid)) *100,2) AS users_with_latest_version -- вычисляем процент пользователей с последней версией приложения
FROM is_latest_version
WHERE platform = 'Букмейт Android' OR platform = 'Букмейт iOS'
GROUP BY os; -- группируем по ОС

/*
	os     |users_with_latest_version|
	-------+-------------------------+
	Android|                    29.35|
	iOS    |                      1.9|
*/

-- Доля пользователей с последней версией приложения составила 29,35% на Android и 1,90% на iOS. 
-- Таким образом, предположение продакт-менеджера о том, что пользователи iOS чаще используют последнюю версию приложения, 
-- не подтверждается: на Android доля таких пользователей значительно выше.



-- Задание 7
-- Как часто пользователи обновляют приложение на каждой из платформ
-- Используя СТЕ, добавляем предыдущую версию приложения в текущую строку для сравнения
WITH previous_rows AS (
    SELECT puid, -- пользователь
    IF(usage_platform_ru LIKE '%iOS','iOS','Android') AS os, -- добавляем столбец со значениями iOS/Android
    app_version, -- версия приложения
    lagInFrame(app_version,1) OVER (PARTITION BY puid,IF(usage_platform_ru LIKE '%iOS','iOS','Android') ORDER BY msk_business_dt_str ROWS BETWEEN 1 PRECEDING AND CURRENT ROW) AS preceding_row -- группируем по пользователю и платформе, сортируем по дате в порядке возрастания и добавляем версию приложения из предыдущей строки
    FROM source_db.audition
    WHERE usage_platform_ru = 'Букмейт Android' OR usage_platform_ru = 'Букмейт iOS') -- оставляем только мобильные приложения
SELECT DISTINCT os, # платформа
    round(avg(countIf(app_version != preceding_row AND preceding_row IS NOT NULL)) OVER (PARTITION BY os),2) AS update_rate -- считаем среднюю частоту обновлений на пользователя и округляем до двух знаков после точки
FROM previous_rows
GROUP BY puid,os; -- группируем по пользователю и платформе

/*
	os     |update_rate|
	-------+-----------+
	iOS    |       2.41|
	Android|        3.2|
*/


-- Пользователи Android чаще обновляют приложение, по сравнению с пользователям iOS: 3.2 против 2.41.


