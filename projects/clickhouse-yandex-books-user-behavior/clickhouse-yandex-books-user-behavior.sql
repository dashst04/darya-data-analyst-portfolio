-- Задание 11
-- Поиск страны и мобильной платформы с максимальным коэффициентом вариации длительности пользовательских сессий
SELECT usage_country_name, -- страна
	   os, -- платформа
	   round(stddevSamp(hours_sessions_long) / avg(hours_sessions_long),2) AS cv -- рассчитываем коэффициент вариации (делим стандартное отклонение на среднее)
FROM ( -- используем подзапрос, чтобы добавить платформу в таблицу
		SELECT *, -- все строки таблицы
		IF(usage_platform_ru LIKE '%iOS','iOS','Android') AS os -- добавляем столбец со значениями iOS/Android
		FROM source_db.audition
		WHERE usage_platform_ru = 'Букмейт Android' OR usage_platform_ru = 'Букмейт iOS') -- оставляем только мобильные приложения 
GROUP BY usage_country_name,os -- группируем по стране и платформе
ORDER BY cv DESC -- сортируем в порядке убывания коэффициента вариации
LIMIT 1; -- оставляем только первую строк, с максимальным значением коэффициента вариации.

/*
	usage_country_name|os     |cv  |
	------------------+-------+----+
	Латвия            |Android|8.46|
 */

-- Наибольший коэффициент вариаци наблюдается среди пользователей Android из Латвии.
