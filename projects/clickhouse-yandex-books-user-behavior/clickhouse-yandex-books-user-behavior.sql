-- Задание 4
-- Количество слушателей и читателей среди пользователей iOS и Android
-- С помощью СТЕ находим основное устройство для каждого пользователя
WITH devices AS (
	SELECT puid, -- пользователь
		   argMax(device,total_hours) AS main_device -- основное устройство
	-- создаем подзапрос в from чтобы найти общее количество часов, проведенных пользователем на каждом из устройств
	FROM (
		SELECT puid, -- пользователь
			IF(usage_platform_ru LIKE '%iOS','iOS','Android') AS device, -- добавляем столбец с устройством (iOS/Android)
			sum(hours) AS total_hours -- считаем количество часов, проведенных пользователем на каждом устройстве
		FROM source_db.audition
		WHERE usage_platform_ru = 'Букмейт Android' OR usage_platform_ru = 'Букмейт iOS' -- оставляем только платформы iOS и Android 
		GROUP BY puid,usage_platform_ru) -- группируем по пользователю и устройству
	GROUP BY puid -- группируем по пользователю
),
-- С помощью СТЕ для каждого пользователя находим какую долю времени он читал книги и слушал аудиокниги
-- При этом исключаем пользователей, у которых нет сессий ни с книгами, ни с аудиокнигами, через != 'Comicbook'
durations AS (
	SELECT a.puid, -- пользователь
		sumIf(a.hours,c.main_content_type = 'Book') / sumIf(a.hours,c.main_content_type != 'Comicbook') AS book_share, -- считаем какую долю времени пользователь проводит за чтением книг
		sumIf(a.hours,c.main_content_type = 'Audiobook') / sumIf(a.hours,c.main_content_type != 'Comicbook') AS audiobook_share -- считаем какую долю времени пользователь проводит за прослушиванием аудиокниг
	FROM source_db.audition a 
	JOIN source_db.content c ON a.main_content_id = c.main_content_id -- присоединяем таблицу content по ключу main_content_id
	GROUP BY puid -- группируем по пользователю
	HAVING sumIf(hours,main_content_type = 'Book') > 0 OR sumIf(hours,main_content_type = 'Audiobook') > 0 -- исключаем пользователей без сессий ни с книгами, ни с аудиокнигами
)
-- Создадим условие с помощью multiIf() и определим, к каком сегменту относится пользователь: "Слушатель", "Читатель" или "Оба"
SELECT multiIf(dr.book_share >= 0.7,'Читатель',dr.audiobook_share >= 0.7,'Слушатель','Оба') AS user_type, -- определяем сегмент пользователя
	   dv.main_device, -- основное устройство пользователя
	   countDistinct(dr.puid) AS total_users -- количество пользователей в каждом сегменте и для каждого типа устройства
FROM durations dr 
JOIN devices dv ON dr.puid = dv.puid -- присоединяем информацию с основным устройством пользователя по ключу puid
GROUP BY user_type,dv.main_device; -- группируем по сегменту и типу устройству

