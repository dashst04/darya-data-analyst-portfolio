    WHERE usage_platform_ru = 'Букмейт Android' OR usage_platform_ru = 'Букмейт iOS'
) AS a ON c.main_content_id = a.main_content_id -- используем подзапрос, чтобы оставить только уникальные main_content_id и не было дублирования строк
