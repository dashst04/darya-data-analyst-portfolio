SELECT
    main_content_name AS title, -- выводим название книги
    main_author_name AS author, -- выводим автора
    ROUND(sum(a.hours), 2) AS total_duration, -- суммируем длительность чтения и прослушивания
    ROUND(sumIf(a.hours, main_content_type = 'Book'), 2) AS book_duration, -- суммируем длительность чтения
    ROUND(sumIf(a.hours, main_content_type = 'Audiobook'), 2) AS audiobook_duration -- суммируем длительность прослушивания
FROM source_db.content AS c
