-- Задание 5
-- Связь между форматом использования приложения (прослушивание или чтение) и днём недели.
SELECT DISTINCT c.main_content_type AS content, -- выводим тип контента
	   round(avgIf(a.hours,toDayOfWeek(a.msk_business_dt_str) <= 5) OVER (PARTITION BY c.main_content_type),2) AS avg_hours_working_days,-- вычисляем среднее время использования контента для будних дней и округляем до двух знаков после точки 
	   round(avgIf(a.hours,toDayOfWeek(a.msk_business_dt_str) > 5) OVER (PARTITION BY c.main_content_type),2) AS avg_hours_weekends -- вычисляем среднее время использования контента для выходных дней и округляем до двух знаков после точки
FROM source_db.audition a 
JOIN source_db.content c ON a.main_content_id = c.main_content_id -- присоединяем таблицу content по ключу main_content_id
WHERE c.main_content_type != 'Comicbook'; -- исключаем Comicbook из анализа

